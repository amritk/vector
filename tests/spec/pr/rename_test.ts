/** The spec's XML, which the contract quotes and pins: `encHex` and `decHex` are its functions. */
const renameTestXml = (enc: string): string =>
  `<rfc version="3"><front><title>T</title></front><middle>
<section anchor="one"><name>One</name>
<t>${enc} MUST work.</t>
<t>decHex MUST work too.</t>
</section></middle></rfc>
`

/** A contract whose main source is specs/s.xml, testing `enc` (whose parameter is `encType`) and `dec`. */
const renameTestContract = (xml: string, enc: string, dec: string, encType: string): string => `{
  "contract": "c1",
  "source": {"title": "T", "main": "s", "sha256": "${sha256Hex(xml)}"},
  "sources": [{"id": "s", "path": "../specs/s.xml"}],
  "target": {"module": "nish/hex"},
  "requirements": [{"id": "R1", "section": "1", "level": "MUST", "quote": "${enc} MUST work."}],
  "functions": [
    {"name": "${enc}", "params": [{"name": "b", "type": "${encType}"}], "returns": "string"},
    {"name": "${dec}", "params": [{"name": "s", "type": "string"}], "returns": "bytes"}
  ],
  "clauses": [
    {"kind": "vector", "id": "V1", "title": "t", "covers": ["R1"],
     "source": {"cite": {"section": "1"}}, "call": "${enc}", "args": [{"hex": "00"}], "expect": {"str": "00"}}
  ]
}
`

/** The test emitted from `contract`, importing `enc` and `dec`. */
const renameTestGenerated = (contract: string, enc: string, dec: string): string =>
  `// Generated by vector.\n${STALE_PREFIX}${sha256Hex(contract)}\nimport { ${dec}, ${enc} } from "../../src/x"\n`

/** The module, exporting `enc`, `dec` and a helper the contract does not test. */
const renameTestModule = (enc: string, dec: string, helper: string): string =>
  `export const ${enc} = (b: bytes): string => ${helper}(b)\nexport const ${dec} = (s: string): bytes => s\nexport const ${helper} = (b: bytes): string => b\n`

/** One way to change the base: what the head does after (or instead of) the rename, and the verdict. */
class RenameTestRow {
  name: string
  /** The name encHex becomes. */
  enc: string
  /** The name decHex becomes. */
  dec: string
  /** The name helperHex becomes. */
  helper: string
  /** The type of encHex's parameter in the head's contract. */
  encType: string
  /** A file to write in the base and keep, "" for none. */
  baseFile: string
  /** Its text. */
  baseText: string
  /** What to do after renaming: "", "write", "delete", "chmod" or "link". */
  act: string
  /** The path it acts on. */
  path: string
  /** The text "write" writes. */
  text: string
  /** The report's problems, or "OK"; a note starting "note:" is the first note. */
  want: string
  constructor(name: string, enc: string, dec: string, want: string) {
    this.name = name
    this.enc = enc
    this.dec = dec
    this.helper = "helperHex"
    this.encType = "bytes"
    this.baseFile = ""
    this.baseText = ""
    this.act = ""
    this.path = ""
    this.text = ""
    this.want = want
  }
}

/** The problem frozen reports for this repository's change touching both sides. */
const RENAME_TEST_BOTH: string =
  "the change touches the spec side (contracts/c.json, specs/s.md, specs/s.xml, test/spec/c_test.ts) and the implementation (src/x.ts): change them in separate PRs"

/** Makes the base, the head the row describes, and returns frozen's verdict. */
const renameTestRun = (row: RenameTestRow): Result<string, string> => {
  const dir = prTestRepo("vector-rename-").orReturn()
  const xml = renameTestXml("encHex")
  const contract = renameTestContract(xml, "encHex", "decHex", "bytes")
  prTestWrite(dir, "specs/s.md", "# S\n\nencHex MUST work.\ndecHex MUST work too.\n").orReturn()
  prTestWrite(dir, "specs/s.xml", xml).orReturn()
  prTestWrite(dir, "contracts/c.json", contract).orReturn()
  prTestWrite(dir, "test/spec/c_test.ts", renameTestGenerated(contract, "encHex", "decHex")).orReturn()
  prTestWrite(dir, "src/x.ts", renameTestModule("encHex", "decHex", "helperHex")).orReturn()
  if (row.baseFile.length > 0) {
    prTestWrite(dir, row.baseFile, row.baseText).orReturn()
  }
  prTestCommit(dir, "base").orReturn()
  prTestGit(dir, ["checkout", "-q", "-b", "work"]).orReturn()

  const xml2 = replaceAll(renameTestXml(row.enc), "decHex", row.dec)
  const contract2 = renameTestContract(xml2, row.enc, row.dec, row.encType)
  prTestWrite(dir, "specs/s.md", `# S\n\n${row.enc} MUST work.\n${row.dec} MUST work too.\n`).orReturn()
  prTestWrite(dir, "specs/s.xml", xml2).orReturn()
  prTestWrite(dir, "contracts/c.json", contract2).orReturn()
  prTestWrite(dir, "test/spec/c_test.ts", renameTestGenerated(contract2, row.enc, row.dec)).orReturn()
  prTestWrite(dir, "src/x.ts", renameTestModule(row.enc, row.dec, row.helper)).orReturn()
  if (row.act === "write") {
    prTestWrite(dir, row.path, row.text).orReturn()
  } else if (row.act === "delete") {
    prTestGit(dir, ["rm", "-q", row.path]).orReturn()
  } else if (row.act === "chmod") {
    runProcess(["chmod", "+x", `${dir}/${row.path}`], "", 10000).orReturn()
  } else if (row.act === "link") {
    runProcess(["ln", "-sf", "x.ts.real", `${dir}/${row.path}`], "", 10000).orReturn()
  }
  const r = frozenCheck(dir, "main", [])
  prTestRemove(dir)
  if (r.isErr()) {
    return Ok(`error: ${r.error}`)
  }
  if (r.value.problems.length > 0) {
    return Ok(r.value.problems.join(" | "))
  }
  return Ok(r.value.notes.length > 0 ? `note: ${r.value.notes.join(" | ")}` : "OK")
}

/** The rows: the one rename that passes, and each neighbour that must not. */
const renameTestRows = (): RenameTestRow[] => {
  const out: RenameTestRow[] = []
  out.push(
    new RenameTestRow(
      "a pure rename across spec, xml, contract, generated test and module passes",
      "hexEncode",
      "decHex",
      "note: passed as a rename: contracts/c.json renames encHex to hexEncode, and the 5 changed files are that rename alone",
    ),
  )
  const none = new RenameTestRow(
    "a both-sides change that renames nothing the contract tests is the plain refusal",
    "encHex",
    "decHex",
    "the change touches the spec side (specs/s.md) and the implementation (src/x.ts): change them in separate PRs",
  )
  none.helper = "hexHelper"
  none.act = "write"
  none.path = "specs/s.md"
  none.text = "# S, changed\n"
  out.push(none)
  let r = new RenameTestRow(
    "an extra edit in the module refuses",
    "hexEncode",
    "decHex",
    `${RENAME_TEST_BOTH} | not a rename alone: src/x.ts: line 4 is not the rename alone`,
  )
  r.act = "write"
  r.path = "src/x.ts"
  r.text = `${renameTestModule("hexEncode", "decHex", "helperHex")}// and more\n`
  out.push(r)
  r = new RenameTestRow(
    "a new name the fork point already uses refuses",
    "hexEncode",
    "decHex",
    `${RENAME_TEST_BOTH} | not a rename alone: notes.md: already names hexEncode at the fork point, so the rename cannot be told from it`,
  )
  r.baseFile = "notes.md"
  r.baseText = "hexEncode is next\n"
  r.act = "write"
  r.path = "notes.md"
  r.text = "hexEncode is next, done\n"
  out.push(r)
  r = new RenameTestRow(
    "an old name the head still uses refuses",
    "hexEncode",
    "decHex",
    `${RENAME_TEST_BOTH} | not a rename alone: notes.md: still names encHex, so the rename is partial`,
  )
  r.baseFile = "notes.md"
  r.baseText = "encHex, then encHex\n"
  r.act = "write"
  r.path = "notes.md"
  r.text = "hexEncode, then encHex\n"
  out.push(r)
  out.push(
    new RenameTestRow(
      "two functions renamed refuses",
      "hexEncode",
      "hexDecode",
      `${RENAME_TEST_BOTH} | not a rename alone: contracts/c.json: no rename: it drops 2 (encHex, decHex) and adds 2 (hexEncode, hexDecode), not one function each`,
    ),
  )
  r = new RenameTestRow(
    "a changed signature refuses",
    "hexEncode",
    "decHex",
    `${RENAME_TEST_BOTH} | not a rename alone: contracts/c.json: no rename: hexEncode has another signature than encHex`,
  )
  r.encType = "string"
  out.push(r)
  r = new RenameTestRow(
    "an added file refuses",
    "hexEncode",
    "decHex",
    `${replaceAll(RENAME_TEST_BOTH, "(src/x.ts)", "(src/x.ts, src/y.ts)")} | not a rename alone: src/y.ts: added by the change`,
  )
  r.act = "write"
  r.path = "src/y.ts"
  r.text = "y\n"
  out.push(r)
  r = new RenameTestRow(
    "a deleted file refuses",
    "hexEncode",
    "decHex",
    `${RENAME_TEST_BOTH} | not a rename alone: notes.md: deleted by the change`,
  )
  r.baseFile = "notes.md"
  r.baseText = "n\n"
  r.act = "delete"
  r.path = "notes.md"
  out.push(r)
  r = new RenameTestRow(
    "a mode change refuses",
    "hexEncode",
    "decHex",
    `${RENAME_TEST_BOTH} | not a rename alone: src/x.ts: its mode changed`,
  )
  r.act = "chmod"
  r.path = "src/x.ts"
  out.push(r)
  r = new RenameTestRow(
    "a file turned into a link refuses",
    "hexEncode",
    "decHex",
    `${RENAME_TEST_BOTH} | not a rename alone: src/x.ts: not a regular file at the fork point and now`,
  )
  r.act = "link"
  r.path = "src/x.ts"
  out.push(r)
  r = new RenameTestRow(
    "renaming an export the contract does not test as well refuses",
    "hexEncode",
    "decHex",
    `${RENAME_TEST_BOTH} | not a rename alone: src/x.ts: line 1 is not the rename alone`,
  )
  r.helper = "hexHelper"
  out.push(r)
  r = new RenameTestRow(
    "a reflowed xml line refuses",
    "hexEncode",
    "decHex",
    `~${RENAME_TEST_BOTH} | not a rename alone: specs/s.xml: line 3 is not the rename alone | contracts/c.json: source s (specs/s.xml) has SHA-256`,
  )
  r.act = "write"
  r.path = "specs/s.xml"
  r.text = replaceAll(renameTestXml("hexEncode"), "<t>hexEncode MUST work.</t>", "<t>hexEncode\nMUST work.</t>")
  out.push(r)
  return out
}

/** Every row through frozen, in a repository of its own. */
const renameTestTable = (t: Suite): Result<boolean, string> => {
  for (const row of renameTestRows()) {
    const got = renameTestRun(row).orReturn()
    if (row.want.startsWith("~")) {
      t.contains(row.name, got, row.want.substring(1))
    } else {
      t.eqStr(row.name, got, row.want)
    }
  }
  return Ok(true)
}

/** The text helpers, on their neighbours. */
const renameTestText = (t: Suite): void => {
  t.eqStr(
    "tokens replace whole identifiers only",
    renameTokens("enc(encX, x.enc, $enc, enc_)", ["enc"], ["e"]),
    "e(encX, x.e, $enc, enc_)",
  )
  t.eqStr("tokens replace at once", renameTokens("a b", ["a", "b"], ["b", "a"]), "b a")
  t.eqStr("tokens at the ends", renameTokens("enc", ["enc"], ["e"]), "e")
  t.ok("has finds a token", renameHas("x enc;", "enc"))
  t.ok("has skips a longer one", !renameHas("encX xenc", "enc"))
  t.eqStr("shas are blanked", renameBlankShas('{"sha256": "abc12", "sha256" :"F0"}'), '{"sha256": "", "sha256" :""}')
  t.eqStr("a non-hex value is kept", renameBlankShas('{"sha256": "xyz"}'), '{"sha256": "xyz"}')
  t.eqStr("another key is kept", renameBlankShas('{"sha": "ab"}'), '{"sha": "ab"}')
  t.eqStr(
    "the stale line is blanked once",
    renameBlankStale(`// a\n${STALE_PREFIX}ab\n${STALE_PREFIX}cd\nx`),
    `// a\n${STALE_PREFIX.substring(0, STALE_PREFIX.length - 1)}\n${STALE_PREFIX}cd\nx`,
  )
  t.eqStr("a stale prefix after code is kept", renameBlankStale(`x ${STALE_PREFIX}ab`), `x ${STALE_PREFIX}ab`)
}

/** renameSameSig on each part of a signature. */
const renameTestSigs = (t: Suite): void => {
  const base = `{"name": "f", "module": "nish/m", "params": [{"name": "b", "type": "bytes"}], "returns": "string"}`
  const rows: string[] = [
    "same apart from the name",
    `{"name": "g", "module": "nish/m", "params": [{"name": "b", "type": "bytes"}], "returns": "string"}`,
    "true",
    "another module",
    `{"name": "g", "module": "nish/n", "params": [{"name": "b", "type": "bytes"}], "returns": "string"}`,
    "false",
    "no module",
    `{"name": "g", "params": [{"name": "b", "type": "bytes"}], "returns": "string"}`,
    "false",
    "another parameter name",
    `{"name": "g", "module": "nish/m", "params": [{"name": "c", "type": "bytes"}], "returns": "string"}`,
    "false",
    "another parameter type",
    `{"name": "g", "module": "nish/m", "params": [{"name": "b", "type": "string"}], "returns": "string"}`,
    "false",
    "another parameter count",
    `{"name": "g", "module": "nish/m", "params": [], "returns": "string"}`,
    "false",
    "another result",
    `{"name": "g", "module": "nish/m", "params": [{"name": "b", "type": "bytes"}], "returns": "bytes"}`,
    "false",
    "another function name override",
    `{"name": "g", "module": "nish/m", "names": {"rust": "g"}, "params": [{"name": "b", "type": "bytes"}], "returns": "string"}`,
    "false",
    "another parameter name override",
    `{"name": "g", "module": "nish/m", "params": [{"name": "b", "type": "bytes", "names": {"rust": "c"}}], "returns": "string"}`,
    "false",
  ]
  for (let i = 0; i < rows.length; i += 3) {
    const a = renameTestFn(base)
    const b = renameTestFn(rows[i + 1])
    t.ok(rows[i], a !== null && b !== null && renameSameSig(a, b) === (rows[i + 2] === "true"))
  }
}

/** The one function of a contract holding `fn`, or null when it does not load. */
const renameTestFn = (fn: string): FnSig | null => {
  const text = `{"contract": "c", "source": {"title": "T", "rfc": 4648}, "target": {"module": "nish/m"},
  "requirements": [{"id": "R1", "section": "1", "level": "MUST", "quote": "q"}], "functions": [${fn}],
  "clauses": [{"kind": "vector", "id": "V1", "title": "t", "covers": ["R1"], "source": {"cite": {"section": "1"}},
    "call": "f", "args": [{"hex": "00"}], "expect": {"str": "00"}}]}`
  const c = contractLoad(text, "c.json")
  if (c.isErr()) {
    console.log(c.error.join("; "))
    return null
  }
  return c.value.functions[0]
}

/** A verdict's refusal, or "" when it has none. */
const renameTestWhy = (v: RenameVerdict): string => {
  const why = v.refusal
  return why === null ? "" : why
}

/** renamePairs across two contracts, and renameCheck called directly. */
const renameTestDirect = (t: Suite): Result<boolean, string> => {
  const dir = prTestRepo("vector-rename-").orReturn()
  const xml = renameTestXml("encHex")
  prTestWrite(dir, "specs/s.xml", xml).orReturn()
  prTestWrite(dir, "contracts/c.json", renameTestContract(xml, "encHex", "decHex", "bytes")).orReturn()
  prTestWrite(dir, "contracts/d.json", renameTestContract(xml, "encHex", "decHex", "bytes")).orReturn()
  prTestWrite(dir, "contracts/e.json", renameTestContract(xml, "fooHex", "decHex", "bytes")).orReturn()
  prTestWrite(dir, "contracts/f.json", renameTestContract(xml, "hexEncode", "decHex", "bytes")).orReturn()
  prTestWrite(dir, "contracts/b.json", "{\n").orReturn()
  prTestCommit(dir, "base").orReturn()
  prTestGit(dir, ["checkout", "-q", "-b", "work"]).orReturn()
  const top = gitdiffTop(dir).orReturn()
  const fork = gitdiffForkPoint(top, "main").orReturn()
  const c = [`${top}/contracts/c.json`, `${top}/contracts/d.json`]
  const none = renamePairs(top, fork, c).orReturn()
  t.ok("no rename, no pairs", none.pairs.length === 0 && none.refusal === null)
  prTestWrite(dir, "contracts/n.json", renameTestContract(xml, "hexEncode", "decHex", "bytes")).orReturn()
  const added = renamePairs(top, fork, [`${top}/contracts/n.json`]).orReturn()
  t.ok("a contract new since the fork point renames nothing", added.pairs.length === 0 && added.refusal === null)
  const xml2 = renameTestXml("hexEncode")
  prTestWrite(dir, "specs/s.xml", xml2).orReturn()
  prTestWrite(dir, "contracts/c.json", renameTestContract(xml2, "hexEncode", "decHex", "bytes")).orReturn()
  prTestWrite(dir, "contracts/d.json", renameTestContract(xml2, "hexEncode", "decHex", "bytes")).orReturn()
  const same = renameCheck(top, fork, ["contracts/c.json", "contracts/d.json", "specs/s.xml"], c, []).orReturn()
  t.ok("two contracts renaming alike are one pair", same.refusal === null && same.pairs.length === 1)
  prTestWrite(dir, "contracts/d.json", renameTestContract(xml2, "encOther", "decHex", "bytes")).orReturn()
  const two = renamePairs(top, fork, c).orReturn()
  t.eqStr(
    "one name renamed two ways refuses",
    renameTestWhy(two),
    "contracts/d.json: no rename: it renames encHex to encOther, but contracts/c.json renames encHex to hexEncode",
  )
  prTestWrite(dir, "contracts/d.json", renameTestContract(xml2, "hexEncode", "decHex", "bytes")).orReturn()
  prTestWrite(dir, "contracts/e.json", renameTestContract(xml2, "encHex", "decHex", "bytes")).orReturn()
  const chain = renamePairs(top, fork, [c[0], c[1], `${top}/contracts/e.json`]).orReturn()
  t.eqStr(
    "a new name that is another's old one refuses",
    renameTestWhy(chain),
    "contracts/e.json: no rename: it renames fooHex to encHex, but contracts/c.json renames encHex to hexEncode",
  )
  prTestWrite(dir, "contracts/e.json", renameTestContract(xml2, "hexEncode", "decHex", "bytes")).orReturn()
  t.eqStr(
    "two old names renamed to one new name refuses",
    renameTestWhy(renamePairs(top, fork, [c[0], `${top}/contracts/e.json`]).orReturn()),
    "contracts/e.json: no rename: it renames fooHex to hexEncode, but contracts/c.json renames encHex to hexEncode",
  )
  prTestWrite(dir, "contracts/f.json", renameTestContract(xml2, "barHex", "decHex", "bytes")).orReturn()
  t.eqStr(
    "an old name that is another's new one refuses",
    renameTestWhy(renamePairs(top, fork, [c[0], `${top}/contracts/f.json`]).orReturn()),
    "contracts/f.json: no rename: it renames hexEncode to barHex, but contracts/c.json renames encHex to hexEncode",
  )
  const dec = `,\n    {"name": "decHex", "params": [{"name": "s", "type": "string"}], "returns": "bytes"}`
  const full = renameTestContract(xml2, "hexEncode", "decHex", "bytes")
  prTestWrite(dir, "contracts/d.json", replaceAll(full, dec, "")).orReturn()
  t.eqStr(
    "a dropped function alone refuses",
    renameTestWhy(renamePairs(top, fork, [c[1]]).orReturn()),
    "contracts/d.json: no rename: it drops 2 (encHex, decHex) and adds 1 (hexEncode), not one function each",
  )
  const xmlKept = renameTestContract(xml, "encHex", "decHex", "bytes")
  prTestWrite(dir, "contracts/d.json", replaceAll(xmlKept, dec, "")).orReturn()
  t.eqStr(
    "one function dropped and none added refuses",
    renameTestWhy(renamePairs(top, fork, [c[1]]).orReturn()),
    "contracts/d.json: no rename: it drops 1 (decHex) and adds none, not one function each",
  )
  const extra = `${dec},\n    {"name": "extraHex", "params": [{"name": "s", "type": "string"}], "returns": "bytes"}`
  prTestWrite(dir, "contracts/d.json", replaceAll(xmlKept, dec, extra)).orReturn()
  t.eqStr(
    "one function added and none dropped refuses",
    renameTestWhy(renamePairs(top, fork, [c[1]]).orReturn()),
    "contracts/d.json: no rename: it drops none and adds 1 (extraHex), not one function each",
  )
  prTestWrite(dir, "contracts/b.json", renameTestContract(xml, "encHex", "decHex", "bytes")).orReturn()
  t.eqStr(
    "a contract that did not load at the fork point refuses",
    renameTestWhy(renamePairs(top, fork, [`${top}/contracts/b.json`]).orReturn()),
    "contracts/b.json: no rename: it is not a contract at the fork point",
  )
  prTestRemove(dir)
  return Ok(true)
}

/** Runs the rename tests. */
export const main = (): i32 => {
  const t = new Suite("spec/pr/rename")
  renameTestText(t)
  renameTestSigs(t)
  const table = renameTestTable(t)
  if (table.isErr()) {
    t.fail("the rename table", table.error)
  }
  const direct = renameTestDirect(t)
  if (direct.isErr()) {
    t.fail("the direct calls", direct.error)
  }
  return t.done()
}
