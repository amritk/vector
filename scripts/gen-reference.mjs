/** The anchor of a schema's `$defs` entry, the same on GitHub and Scalar. */
const defAnchor = (name) =>
  `def-${name.replace(/[^A-Za-z0-9]+/g, "-").toLowerCase()}`;

/** A schema as a type, `string`, `integer[]`, `"pre" | "post"`, with `$ref`s linked to their sections. */
const schemaType = (s) => {
  if (s === true || s === undefined) {
    return "any";
  }
  if (s === false) {
    return "never";
  }
  if (s.$ref) {
    const name = /^#\/\$defs\/(.+)$/.exec(s.$ref)?.[1];
    return name ? `[${code(name)}](#${defAnchor(name)})` : code(s.$ref);
  }
  if (s.const !== undefined) {
    return code(JSON.stringify(s.const));
  }
  if (s.enum) {
    return s.enum.map((v) => code(JSON.stringify(v))).join(" \\| ");
  }
  const alts = s.anyOf ?? s.oneOf;
  if (alts) {
    return alts.map(schemaType).join(" \\| ");
  }
  const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : [];
  return (
    types
      .map((t) => {
        if (t === "array") {
          const item = schemaType(s.items);
          return /\\\|/.test(item) ? `array of ${item}` : `${item}[]`;
        }
        if (
          t === "object" &&
          s.additionalProperties &&
          typeof s.additionalProperties === "object" &&
          !s.properties
        ) {
          return `map of ${schemaType(s.additionalProperties)}`;
        }
        return code(t);
      })
      .join(" \\| ") || "any"
  );
};

/** The constraints a schema puts on its value, as a sentence or "". */
const constraints = (s) => {
  if (!s || typeof s !== "object") {
    return "";
  }
  const out = [];
  const add = (key, text) => {
    if (s[key] !== undefined) {
      out.push(text(s[key]));
    }
  };
  add("pattern", (v) => `matches ${code(v)}`);
  add("format", (v) => `format ${code(v)}`);
  add("minimum", (v) => `at least ${v}`);
  add("exclusiveMinimum", (v) => `more than ${v}`);
  add("maximum", (v) => `at most ${v}`);
  add("exclusiveMaximum", (v) => `less than ${v}`);
  add("minLength", (v) => `at least ${v} characters`);
  add("maxLength", (v) => `at most ${v} characters`);
  add("minItems", (v) => `at least ${v} items`);
  add("maxItems", (v) => `at most ${v} items`);
  add("uniqueItems", (v) => (v ? "items unique" : "items may repeat"));
  add("default", (v) => `default ${code(JSON.stringify(v))}`);
  if (s.type === "array" && s.items && typeof s.items === "object") {
    const inner = constraints({ ...s.items, default: undefined });
    if (inner) {
      out.push(`each item ${inner.replace(/\.$/, "")}`);
    }
  }
  return out.length > 0 ? `${out.join("; ")}.` : "";
};

/** The inline object a schema describes, directly, as its array's items or as anyOf variants. */
const inlineObjects = (s, at) => {
  if (!s || typeof s !== "object" || s.$ref) {
    return [];
  }
  if (s.properties) {
    return [{ schema: s, at }];
  }
  if (s.type === "array" || s.items) {
    return inlineObjects(s.items, `${at}[]`);
  }
  const alts = s.anyOf ?? s.oneOf;
  if (alts) {
    return alts.flatMap((a, i) => {
      const kind = a?.properties?.kind?.const;
      return inlineObjects(
        a,
        kind !== undefined
          ? `${at} (kind ${JSON.stringify(kind)})`
          : `${at} (variant ${i + 1})`,
      );
    });
  }
  if (s.additionalProperties && typeof s.additionalProperties === "object") {
    return inlineObjects(s.additionalProperties, `${at}{}`);
  }
  return [];
};

/** The anchor of a nested object's section. */
const pathAnchor = (scope, at) =>
  `${scope}-${at}`
    .replace(/[^A-Za-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();

/**
 * An object schema's sections: the table of its properties, then a section for
 * each object nested in it, by path (`units[].params[]`).
 */
const objectSections = (s, at, scope, level) => {
  const required = new Set(s.required ?? []);
  const nested = [];
  const rows = Object.entries(s.properties ?? {}).map(([name, p]) => {
    const inner = inlineObjects(p, at ? `${at}.${name}` : name);
    nested.push(...inner);
    let type = schemaType(p);
    if (inner.length > 0 && !p?.anyOf && !p?.oneOf) {
      const list = (p.type === "array" || p.items) && !p.properties;
      type = `[${list ? "object[]" : "object"}](#${pathAnchor(scope, inner[0].at)})`;
    }
    const desc = [p?.description ?? "", constraints(p)]
      .filter(Boolean)
      .join(" ");
    return `| ${code(name)} | ${type} | ${required.has(name) ? "yes" : "no"} | ${cell(desc)} |`;
  });
  const parts = [];
  if (rows.length > 0) {
    parts.push(
      [
        "| Property | Type | Required | Description |",
        "| --- | --- | --- | --- |",
        ...rows,
      ].join("\n"),
    );
  }
  if (s.additionalProperties === false) {
    parts.push("No other property is allowed.");
  } else if (
    s.additionalProperties &&
    typeof s.additionalProperties === "object"
  ) {
    parts.push(`Any other property is ${schemaType(s.additionalProperties)}.`);
  }
  for (const n of nested) {
    parts.push(
      `<a id="${pathAnchor(scope, n.at)}"></a>`,
      `${"#".repeat(level)} ${code(n.at)}`,
      ...(n.schema.description ? [escapeProse(n.schema.description)] : []),
      ...objectSections(n.schema, n.at, scope, Math.min(level + 1, 4)),
    );
  }
  return parts;
};

/** One schema, or one `$defs` entry: its description, its type and its properties. */
const schemaBody = (s, scope, level) => {
  const parts = [];
  if (s.description) {
    parts.push(escapeProse(s.description));
  }
  if (s.properties) {
    parts.push(...objectSections(s, "", scope, level));
    return parts;
  }
  const alts = s.anyOf ?? s.oneOf;
  if (alts) {
    parts.push(`${s.oneOf ? "Exactly one" : "One or more"} of:`);
    parts.push(
      alts
        .map((a, i) => {
          const kind = a?.properties?.kind?.const;
          if (a?.properties) {
            const at =
              kind !== undefined
                ? `(kind ${JSON.stringify(kind)})`
                : `(variant ${i + 1})`;
            return `- [an object ${code(at.slice(1, -1))}](#${pathAnchor(scope, at)})${a.description ? `: ${cell(a.description)}` : ""}`;
          }
          const extra = constraints(a);
          return `- ${schemaType(a)}${a?.description ? `: ${cell(a.description)}` : ""}${extra ? ` (${extra.replace(/\.$/, "")})` : ""}`;
        })
        .join("\n"),
    );
    alts.forEach((a, i) => {
      if (a?.properties) {
        const kind = a.properties.kind?.const;
        const at =
          kind !== undefined
            ? `(kind ${JSON.stringify(kind)})`
            : `(variant ${i + 1})`;
        parts.push(
          `<a id="${pathAnchor(scope, at)}"></a>`,
          `${"#".repeat(level)} ${code(at.slice(1, -1))}`,
          ...objectSections(a, at, scope, Math.min(level + 1, 4)),
        );
      }
    });
    return parts;
  }
  const extra = constraints(s);
  parts.push(
    `${schemaType(s)}${extra ? `; ${extra}` : ""}`.replace(/^(.)/, (c) =>
      c.toUpperCase(),
    ),
  );
  return parts;
};

const renderFormat = (file) => {
  let s;
  try {
    s = JSON.parse(read(file));
  } catch (e) {
    fail(`${file}: not JSON: ${e.message}`);
  }
  const name = path.posix.basename(file, ".json");
  const parts = [`# ${s.title ? `${s.title} (${name}.json)` : `${name}.json`}`];
  parts.push(
    `The JSON Schema in [${file}](${repoUrl}/${file}), as a reference.`,
  );
  parts.push(...schemaBody({ ...s, $defs: undefined }, "root", 3));
  const defs = Object.entries(s.$defs ?? s.definitions ?? {});
  if (defs.length > 0) {
    parts.push("## Definitions");
    for (const [dn, ds] of defs) {
      parts.push(
        `<a id="${defAnchor(dn)}"></a>`,
        `### ${code(dn)}`,
        ...schemaBody(ds, defAnchor(dn), 4),
      );
    }
  }
  return page(header(file, "the schema"), parts);
};

