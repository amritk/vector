const posix = (p) => p.split(path.sep).join("/");
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");

/** Files under `dir` (relative to the repo) whose names pass `keep`, sorted. */
const listFiles = (dir, keep = () => true) => {
  const full = path.join(root, dir);
  if (!fs.existsSync(full)) {
    return [];
  }
  return fs
    .readdirSync(full, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile() && keep(e.name))
    .map((e) => posix(path.relative(root, path.join(e.parentPath, e.name))))
    .sort();
};

