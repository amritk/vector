// Generate docs/reference/** and its routes in scalar.config.json from the
// source, and check that they are up to date.
//
//   node scripts/gen-reference.mjs                    write the pages and the /reference routes
//   node scripts/gen-reference.mjs --check            write nothing; exit 1 if anything is stale
//   node scripts/gen-reference.mjs --update-baseline  also rewrite scripts/undocumented.txt,
//                                                     refusing to add a line to it
//   node scripts/gen-reference.mjs --grow-baseline    the same, but allowed to add lines
//   node scripts/gen-reference.mjs --check --base REF also exit 1 if scripts/undocumented.txt
//                                                     lists a line that REF's copy does not
//
// The reference has three parts, each read from what defines it, so the
// script needs no list of today's commands, schemas or modules:
//
//   Command line  the command tree src/index.ts declares on `nish/cli-args`,
//                 read from the TypeScript AST: `new Cli(...)`, `cli.group`,
//                 `cli.command`, `cli.flag`, `cli.argument` and the rest. Each
//                 call that is handed the cli is followed into the function
//                 it names, in this file or through a named relative import,
//                 with the cli and the parent handle bound to its parameters.
//                 A shape it cannot follow, a handle it cannot resolve, a
//                 duplicate sibling, or a count of `.command(`/`.group(` calls
//                 that differs from the tree is an error, not a missing page.
//                 The exit codes are src/core/diag.ts's `EXIT_*`.
//   File formats  one page per schemas/*.json.
//   Modules       one page per src/**/*.ts, by TypeDoc, with nish's runtime
//                 declarations and its `nish/*` → .nish/std/* mapping. A public
//                 declaration without its documentation is a gap; the gaps
//                 must equal scripts/undocumented.txt, which only shrinks.
//
// Every page starts with a "Do not edit by hand" comment and is a function of
// the source alone, byte for byte. In scalar.config.json only the "/reference"
// route is regenerated; every other line is kept as written. docs/README.md
// ("The reference") states the rules this enforces.
