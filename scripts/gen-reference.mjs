const pageRoute = (title, filepath) => ({ type: "page", title, filepath });

/** The "/reference" route: the overview, then a group per part. */
const referenceRoute = (tree, formats, modules) => {
  const commands = { "/": pageRoute("Overview", commandLinePage) };
  for (const { node: n, words } of commandsOf(tree)) {
    if (n.kind === "command") {
      commands[`/${words.join("-")}`] = pageRoute(
        `${tree.root.name} ${words.join(" ")}`,
        commandPage(words),
      );
    }
  }
  const formatRoutes = Object.fromEntries(
    formats.map((f) => [
      `/${path.posix.basename(f.file, ".json")}`,
      pageRoute(path.posix.basename(f.file), formatPage(f.file)),
    ]),
  );
  const moduleRoutes = Object.fromEntries(
    modules.map((m) => [
      `/${moduleName(m.file).replace(/\//g, "-")}`,
      pageRoute(moduleName(m.file), modulePage(m.file)),
    ]),
  );
  return {
    type: "group",
    title: "Reference",
    children: {
      "/": pageRoute("Overview", `${outDir}/index.md`),
      "/command-line": {
        type: "group",
        title: "Command line",
        children: commands,
      },
      "/formats": {
        type: "group",
        title: "File formats",
        children: formatRoutes,
      },
      "/modules": { type: "group", title: "Modules", children: moduleRoutes },
    },
  };
};

const oneLine = (v) => {
  if (Array.isArray(v)) {
    return `[${v.map(oneLine).join(", ")}]`;
  }
  if (v === null || typeof v !== "object") {
    return JSON.stringify(v);
  }
  const kv = Object.entries(v).map(
    ([k, x]) => `${JSON.stringify(k)}: ${oneLine(x)}`,
  );
  return kv.length > 0 ? `{ ${kv.join(", ")} }` : "{}";
};

/** JSON in the file's layout: an object or array on one line when it fits in `width`. */
const printJson = (value, indent, prefix, suffix) => {
  const one = oneLine(value);
  if (
    typeof value !== "object" ||
    value === null ||
    indent + prefix.length + one.length + suffix.length <= width
  ) {
    return `${" ".repeat(indent)}${prefix}${one}${suffix}`;
  }
  const pad = " ".repeat(indent);
  const entries = Array.isArray(value)
    ? value.map((v) => ["", v])
    : Object.entries(value);
  const [open, close] = Array.isArray(value) ? ["[", "]"] : ["{", "}"];
  const lines = entries.map(([k, v], i) =>
    printJson(
      v,
      indent + 2,
      Array.isArray(value) ? "" : `${JSON.stringify(k)}: `,
      i < entries.length - 1 ? "," : "",
    ),
  );
  return `${pad}${prefix}${open}\n${lines.join("\n")}\n${pad}${close}${suffix}`;
};

const indentOf = (line) => /^ */.exec(line)[0].length;

/**
 * scalar.config.json with its "/reference" route regenerated and every other
 * line kept byte for byte. The route must be a child of the "/" group, written
 * as `"/reference": {` on a line of its own.
 */
const configText = (text, route) => {
  const config = JSON.parse(text);
  const children = config.navigation?.routes?.["/"]?.children;
  if (!children || !("/reference" in children)) {
    fail(
      `${configFile}: navigation.routes["/"].children has no "/reference" route to regenerate`,
    );
  }
  const lines = text.split("\n");
  const open = lines.findIndex((l) =>
    l.trimStart().startsWith('"/reference": {'),
  );
  if (open < 0) {
    fail(
      `${configFile}: the "/reference" route is not written as \`"/reference": {\` on a line of its own`,
    );
  }
  const indent = indentOf(lines[open]);
  const close = /\}\s*,?$/.test(lines[open])
    ? open
    : lines.findIndex(
        (l, i) => i > open && indentOf(l) === indent && /^\s*\},?$/.test(l),
      );
  const comma = lines[close].trimEnd().endsWith(",") ? "," : "";
  const out = [
    ...lines.slice(0, open),
    printJson(route, indent, '"/reference": ', comma),
    ...lines.slice(close + 1),
  ].join("\n");
  // What was spliced as text must parse to what was meant.
  children["/reference"] = route;
  if (JSON.stringify(JSON.parse(out)) !== JSON.stringify(config)) {
    fail(
      `${configFile}: the regenerated "/reference" route does not parse back to the route meant`,
    );
  }
  return out;
};

/** Every Markdown file a route names, which a routed page links relatively. */
const routedFiles = (config) => {
  const out = new Set();
  const walk = (node) => {
    if (node && typeof node === "object") {
      if (typeof node.filepath === "string") {
        out.add(node.filepath);
      }
      for (const v of Object.values(node)) {
        walk(v);
      }
    }
  };
  walk(config.navigation);
  return out;
};

// ---- The baseline -------------------------------------------------------------

const baselineHeader = `# Public declarations of src/ that lack their documentation.
#
# This list only shrinks. \`node scripts/gen-reference.mjs --check\` fails on a gap
# it does not list and on a line that is no longer a gap: document the
# declaration and delete its line. \`--update-baseline\` rewrites the file and
# refuses to add a line; \`--grow-baseline\` adds them, only for a change to the rule.
# docs/README.md -> "The reference" states the rule.
#
#   module.Name.member     the declaration has no doc comment
#   module.Name#param:p    parameter p has no @param
#   module.Name#returns    a return type other than void or never has no @returns
`;

const baselineText = (gaps) =>
  `${baselineHeader}${gaps.length > 0 ? "\n" : ""}${gaps.map((g) => `${g}\n`).join("")}`;

const baselineRead = () => {
  const full = path.join(root, baselineFile);
  return fs.existsSync(full) ? fs.readFileSync(full, "utf8") : "";
};

/** A baseline's entries: its lines that are neither blank nor a comment. */
const baselineEntries = (text) =>
  new Set(text.split("\n").filter((l) => l.trim() && !l.startsWith("#")));

const baselineLines = () => baselineEntries(baselineRead());

/** The entries of `headText` that `baseText` lacks, in order: how a baseline grew. */
const baselineGrowth = (baseText, headText) => {
  const base = baselineEntries(baseText);
  return [...baselineEntries(headText)].filter((l) => !base.has(l));
};

// `--check` alone compares the gaps with the baseline as the branch has it,
// which a branch that adds a gap and its line together passes. `--base REF`
// also compares the baseline with REF's, the PR's base, so the list only
// shrinks across a merge. A grown line is reported even when --grow-baseline
// wrote it: that change to the rule is one a reviewer passes by name.
const BASELINE_GROWTH_CASES = [
  // [base, head, the growth]
  ["", "", []],
  ["# h\na\nb\n", "# h\na\n", []],
  ["# h\na\nb\n", "# other header\na\nb\n", []],
  ["a\n", "a\nc\n", ["c"]],
  ["", "# h\n\nx\ny\n", ["x", "y"]],
  ["a\nb\n", "b\nd\na\n", ["d"]],
];

/** Fail unless baselineGrowth gives each case's growth: the base check tests itself. */
const baselineGrowthSelfTest = () => {
  for (const [base, head, want] of BASELINE_GROWTH_CASES) {
    const got = baselineGrowth(base, head);
    if (got.join("\n") !== want.join("\n")) {
      fail(
        `the baseline growth check is broken: for base ${JSON.stringify(base)} and head ${JSON.stringify(head)} it found [${got.join(", ")}], not [${want.join(", ")}]`,
      );
    }
  }
};

/** REF's copy of the baseline ("" when REF has none), or null when REF names no commit. */
const baselineAt = (ref) => {
  const git = (...args) =>
    execFileSync("git", args, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
  try {
    git("rev-parse", "--verify", "--quiet", `${ref}^{commit}`);
  } catch {
    return null;
  }
  try {
    git("cat-file", "-e", `${ref}:${baselineFile}`);
  } catch {
    return "";
  }
  return git("show", `${ref}:${baselineFile}`);
};

/** The baseline's disagreements with the gaps found, one line each. */
const baselineProblems = (gaps) => {
  const listed = baselineLines();
  const found = new Set(gaps);
  const problems = [];
  for (const g of gaps) {
    if (!listed.has(g)) {
      problems.push(
        `undocumented: ${g}: a public declaration needs a doc comment, a @param per parameter and a @returns for a non-void return`,
      );
    }
  }
  for (const l of listed) {
    if (!found.has(l)) {
      problems.push(
        `no longer a gap: ${l}: delete its line from ${baselineFile}`,
      );
    }
  }
  if (problems.length === 0 && baselineRead() !== baselineText(gaps)) {
    problems.push(
      `stale: ${baselineFile} (its header or order); run \`node scripts/gen-reference.mjs --update-baseline\``,
    );
  }
  return problems;
};

// ---- Main -----------------------------------------------------------------------

const main = async () => {
  const args = process.argv.slice(2);
  const known = ["--check", "--update-baseline", "--grow-baseline"];
  let base;
  const unknown = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--base" && i + 1 < args.length) {
      base = args[++i];
    } else if (args[i].startsWith("--base=")) {
      base = args[i].slice("--base=".length);
    } else if (!known.includes(args[i])) {
      unknown.push(args[i]);
    }
  }
  const check = args.includes("--check");
  const grow = args.includes("--grow-baseline");
  const updateBaseline = grow || args.includes("--update-baseline");
  const usage =
    unknown.length > 0
      ? `unknown argument ${unknown.join(" ")}`
      : check && updateBaseline
        ? "--check writes nothing"
        : base !== undefined && (!check || base === "")
          ? "--base takes a ref and goes with --check"
          : "";
  if (usage !== "") {
    console.error(
      `gen-reference: ${usage}; the flags are --check [--base REF], --update-baseline or --grow-baseline`,
    );
    process.exit(2);
  }
  baselineGrowthSelfTest();
  let baseText = "";
  if (base !== undefined) {
    const at = baselineAt(base);
    if (at === null) {
      console.error(
        `gen-reference: --base ${base} names no commit here; fetch it first`,
      );
      process.exit(2);
    }
    baseText = at;
  }

  const tree = readCommandTree();
  const exits = readExitCodes();
  const files = sourceFiles();
  const { project, gaps } = await readProject(files);

  if (updateBaseline) {
    const added = gaps.filter((g) => !baselineLines().has(g));
    if (added.length > 0 && !grow) {
      for (const g of added) {
        console.error(
          `gen-reference: undocumented: ${g}: document it; ${baselineFile} only shrinks`,
        );
      }
      console.error(
        "gen-reference: --update-baseline adds no line; only a change to the rule itself may pass --grow-baseline, and its PR shows each added line",
      );
      process.exit(1);
    }
    for (const g of added) {
      console.log(`gen-reference: grows ${baselineFile}: ${g}`);
    }
  }

  const formats = schemaFiles().map((file) => {
    let description = "";
    try {
      description = JSON.parse(read(file)).description ?? "";
    } catch {}
    return { file, description };
  });
  const byFile = modulesByFile(project);
  const route = referenceRoute(
    tree,
    formats,
    files.map((file) => ({ file })),
  );
  const configBefore = read(configFile);
  const configAfter = configText(configBefore, route);
  const routed = routedFiles(JSON.parse(configAfter));

  const want = new Map();
  want.set(commandLinePage, renderCommandLine(tree, exits));
  for (const { node: n, words } of commandsOf(tree)) {
    if (n.kind === "command") {
      want.set(commandPage(words), renderCommand(tree, words, n));
    }
  }
  for (const f of formats) {
    want.set(formatPage(f.file), renderFormat(f.file));
  }
  const modules = files.map((file) => {
    const { text, lead } = renderModule(file, byFile.get(file), routed);
    want.set(modulePage(file), text);
    return { file, lead };
  });
  want.set(`${outDir}/index.md`, renderIndex(tree, formats, modules, exits));

  const have = listFiles(outDir);
  const problems = [];
  for (const [file, text] of [...want].sort(([a], [b]) => (a < b ? -1 : 1))) {
    const full = path.join(root, file);
    if (!fs.existsSync(full)) {
      problems.push(`missing: ${file}`);
    } else if (fs.readFileSync(full, "utf8") !== text) {
      problems.push(`stale: ${file}`);
    }
  }
  for (const file of have) {
    if (!want.has(file)) {
      problems.push(`extra: ${file}`);
    }
  }
  if (configAfter !== configBefore) {
    problems.push(`stale: ${configFile} (the /reference routes)`);
  }
  const gapProblems = updateBaseline ? [] : baselineProblems(gaps);
  const grown =
    base === undefined ? [] : baselineGrowth(baseText, baselineRead());

  if (check) {
    for (const p of [...problems, ...gapProblems]) {
      console.error(`gen-reference: ${p}`);
    }
    if (problems.length > 0) {
      console.error(
        "gen-reference: the reference is out of date; run `node scripts/gen-reference.mjs`",
      );
    }
    if (gapProblems.length > 0) {
      console.error(
        `gen-reference: the documentation gaps disagree with ${baselineFile}, which only shrinks`,
      );
    }
    for (const g of grown) {
      console.error(
        `gen-reference: grown: ${g}: ${baselineFile} lists it and ${base}'s copy does not; document the declaration instead`,
      );
    }
    if (grown.length > 0) {
      console.error(
        `gen-reference: ${baselineFile} grew against ${base}; it only shrinks, and only a change to the rule itself adds a line`,
      );
    }
    if (problems.length > 0 || gapProblems.length > 0 || grown.length > 0) {
      process.exit(1);
    }
    console.log(
      `gen-reference: ${want.size} pages and their routes are up to date; ${gaps.length} gaps, each listed${base === undefined ? "" : `; ${baselineFile} has not grown against ${base}`}`,
    );
    return;
  }
  for (const file of have) {
    if (!want.has(file)) {
      fs.rmSync(path.join(root, file));
    }
  }
  for (const [file, text] of want) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    fs.writeFileSync(path.join(root, file), text);
  }
  fs.writeFileSync(path.join(root, configFile), configAfter);
  console.log(
    `gen-reference: wrote ${want.size} pages; ${problems.length} changed`,
  );
  if (updateBaseline) {
    fs.writeFileSync(path.join(root, baselineFile), baselineText(gaps));
    console.log(`gen-reference: wrote ${baselineFile}; ${gaps.length} gaps`);
  } else if (gapProblems.length > 0) {
    for (const p of gapProblems) {
      console.error(`gen-reference: ${p}`);
    }
    process.exit(1);
  }
};

try {
  await main();
} catch (e) {
  if (e instanceof GenError) {
    console.error(`gen-reference: ${e.message}`);
    process.exit(1);
  }
  throw e;
}
