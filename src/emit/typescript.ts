import type { FunctionUnit, Program, Ty } from "../lang/ast.ts";
import { prettyExpr } from "../report/pretty.ts";

// Emits runnable TypeScript from a verified Program. The emitted source is a
// direct transliteration of the exact AST the solver proved, with each
// `requires` clause materialized as a runtime guard — the "throws on invalid
// input" behavior the spec asked for. What is proven vs enforced is spelled
// out in each function's JSDoc.

const TS_TYPES: Record<Ty, string> = {
  Real: "number",
  Int: "number",
  Bool: "boolean",
};

export function emitTypeScript(program: Program): string {
  const functions = [...program.functions].sort((a, b) => a.layer - b.layer);
  const header = `// Generated by vector from program "${program.programName}".
// Every postcondition below was proven by Z3 over exact rationals for ALL
// finite inputs satisfying the preconditions, then cross-checked against
// float64 execution (postconditions and callee guards) on sampled boundary +
// random inputs — a sampling check, not a proof. Domain guards reject
// NaN/Infinity, Int args that are not safe integers and non-boolean Bool
// args; preconditions are enforced at runtime via throws.
`;
  return `${header}\n${functions.map(emitFunction).join("\n\n")}\n`;
}

// `purpose` is free text landing inside a JSDoc block: fold it to one line and
// break any `*/` so it cannot terminate the comment and leak into the code.
// (axiomIds are pattern-restricted at the schema/shape gate; rendered
// expressions space-separate every token, so neither can form `*/` or a quote.)
function jsdocSafe(text: string): string {
  return text.replace(/\s+/g, " ").replace(/\*\//g, "*\\/").trim();
}

function emitFunction(fn: FunctionUnit): string {
  const params = fn.params
    .map((p) => `${p.name}: ${TS_TYPES[p.type]}`)
    .join(", ");
  const doc = [
    "/**",
    ` * ${jsdocSafe(fn.purpose)}`,
    ` * Layer ${fn.layer} — Hoare triple proven by Z3:`,
    ...fn.requires.map(
      (c) => ` *   requires ${c.axiomId}: ${prettyExpr(c.expr, "math")}`,
    ),
    ...fn.ensures.map(
      (c) => ` *   ensures  ${c.axiomId}: ${prettyExpr(c.expr, "math")}`,
    ),
    " */",
  ].join("\n");
  // Domain guards: the proof is over finite reals / integers, so the emitted
  // code must reject NaN, ±Infinity, and non-integer Int args — otherwise a
  // caller could pass a value the proof never quantified over (NaN breaks every
  // equality; a fractional "Int" breaks integer reasoning). Int args must be
  // *safe* integers: at 2^53 and beyond a double no longer holds every integer,
  // so integer arithmetic on the argument is not the arithmetic that was proven.
  // Bool args are checked too — an untyped caller passing 0 or "false" would
  // otherwise take a branch the proof assigned to a different truth value.
  const domainGuards = fn.params.flatMap((p) => {
    if (p.type === "Int") {
      return [
        `  if (!Number.isSafeInteger(${p.name})) {`,
        `    throw new RangeError("domain violated: ${p.name} must be a safe integer");`,
        "  }",
      ];
    }
    if (p.type === "Real") {
      return [
        `  if (!Number.isFinite(${p.name})) {`,
        `    throw new RangeError("domain violated: ${p.name} must be a finite number");`,
        "  }",
      ];
    }
    return [
      `  if (typeof ${p.name} !== "boolean") {`,
      `    throw new RangeError("domain violated: ${p.name} must be a boolean");`,
      "  }",
    ];
  });
  const guards = fn.requires.map((c) =>
    [
      `  if (!(${prettyExpr(c.expr, "ts")})) {`,
      `    throw new RangeError("requires violated [${c.axiomId}]: ${prettyExpr(c.expr, "math")}");`,
      "  }",
    ].join("\n"),
  );
  const body = `  return ${prettyExpr(fn.body, "ts")};`;
  return [
    doc,
    `export function ${fn.name}(${params}): ${TS_TYPES[fn.returnType]} {`,
    ...domainGuards,
    ...guards,
    body,
    "}",
  ].join("\n");
}
