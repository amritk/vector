/**
 * `verify/emit/typescript` — the TypeScript a proven program compiles to: a
 * direct transliteration of the expressions the solver proved, with domain
 * guards on every parameter and each requires clause as a runtime throw.
 */

import { FnUnit, Program } from "../lang/ast"
import { prettyMath, prettyTs } from "../lang/pretty"

/**
 * The TypeScript type of a vector-lang type.
 *
 * @param ty `Real`, `Int` or `Bool`
 * @returns `number` or `boolean`
 */
export const tsType = (ty: string): string => (ty === "Bool" ? "boolean" : "number")

const tsIsSpace = (c: i32): boolean => c === 32 || c === 9 || c === 10 || c === 13 || c === 11 || c === 12

/**
 * Makes free text safe inside a JSDoc block: whitespace runs fold to one
 * space, the ends are trimmed, and `*\/` cannot close the comment.
 *
 * @param text the text
 * @returns the folded text
 */
export const jsdocSafe = (text: string): string => {
  let out = ""
  let pendingSpace = false
  for (let i = 0; i < toI32(text.length); i++) {
    const c = text.charCodeAt(i)
    if (tsIsSpace(c)) {
      pendingSpace = out.length > 0
    } else {
      if (pendingSpace) {
        out = `${out} `
        pendingSpace = false
      }
      if (c === 47 && out.length > 0 && out.charCodeAt(toI32(out.length) - 1) === 42) {
        out = `${out}\\/`
      } else {
        out = out + text.slice(i, i + 1)
      }
    }
  }
  return out
}

const tsDomainGuard = (lines: string[], name: string, ty: string): void => {
  if (ty === "Int") {
    lines.push(`  if (!Number.isSafeInteger(${name})) {`)
    lines.push(`    throw new RangeError("domain violated: ${name} must be a safe integer");`)
  } else if (ty === "Real") {
    lines.push(`  if (!Number.isFinite(${name})) {`)
    lines.push(`    throw new RangeError("domain violated: ${name} must be a finite number");`)
  } else {
    lines.push(`  if (typeof ${name} !== "boolean") {`)
    lines.push(`    throw new RangeError("domain violated: ${name} must be a boolean");`)
  }
  lines.push("  }")
}

const tsFunction = (fn: FnUnit): string => {
  const lines: string[] = []
  lines.push("/**")
  lines.push(` * ${jsdocSafe(fn.purpose)}`)
  lines.push(` * Layer ${fn.layer} — Hoare triple proven by Z3:`)
  for (const c of fn.requires) {
    lines.push(` *   requires ${c.axiomId}: ${prettyMath(c.expr)}`)
  }
  for (const c of fn.ensures) {
    lines.push(` *   ensures  ${c.axiomId}: ${prettyMath(c.expr)}`)
  }
  lines.push(" */")
  const params: string[] = []
  for (const p of fn.params) {
    params.push(`${p.name}: ${tsType(p.ty)}`)
  }
  lines.push(`export function ${fn.name}(${params.join(", ")}): ${tsType(fn.returnType)} {`)
  for (const p of fn.params) {
    tsDomainGuard(lines, p.name, p.ty)
  }
  for (const c of fn.requires) {
    lines.push(`  if (!(${prettyTs(c.expr)})) {`)
    lines.push(`    throw new RangeError("requires violated [${c.axiomId}]: ${prettyMath(c.expr)}");`)
    lines.push("  }")
  }
  lines.push(`  return ${prettyTs(fn.body)};`)
  lines.push("}")
  return lines.join("\n")
}

/**
 * The program's functions, ordered by layer; functions of one layer keep their order.
 *
 * @param program the program
 * @returns the functions, lowest layer first
 */
export const functionsByLayer = (program: Program): FnUnit[] => {
  const out: FnUnit[] = []
  let layer = 0x7fffffff
  for (const fn of program.functions) {
    layer = Math.min(layer, fn.layer)
  }
  let placed = 0
  while (placed < toI32(program.functions.length)) {
    let next = 0x7fffffff
    for (const fn of program.functions) {
      if (fn.layer === layer) {
        out.push(fn)
        placed = placed + 1
      } else if (fn.layer > layer) {
        next = Math.min(next, fn.layer)
      }
    }
    layer = next
  }
  return out
}

/**
 * Emits a proven program as TypeScript.
 *
 * @param program the program
 * @returns the module's source, ending in a newline
 */
export const emitTypeScript = (program: Program): string => {
  const parts: string[] = []
  for (const fn of functionsByLayer(program)) {
    parts.push(tsFunction(fn))
  }
  const header = [
    `// Generated by vector from program "${program.programName}".`,
    "// Every postcondition below was proven by Z3 over exact rationals for ALL",
    "// finite inputs satisfying the preconditions, then cross-checked against",
    "// float64 execution (postconditions and callee guards) on sampled boundary +",
    "// random inputs — a sampling check, not a proof. Every Int +, - and * was",
    "// proven to stay within ±(2^53−1), so Int arithmetic is exact in float64.",
    "// Domain guards reject NaN/Infinity, Int args that are not safe integers",
    "// and non-boolean Bool args; preconditions are enforced at runtime via",
    "// throws.",
    "",
  ].join("\n")
  return `${header}\n${parts.join("\n\n")}\n`
}
